/** 允许出现、且很有用的客观信息类型。 */
export const COPY_ALLOWED_KINDS: readonly string[] = [
  "地点 / 街区 / 城市（资料里出现过的真实地名）",
  "季节、节气、时间感（深秋、傍晚、开春、凌晨）",
  "客观风格 tag（复古潮流、街头感、侘寂、户外机能）",
  "资料里明确提到的商品类别、材质、工艺、尺寸、产地",
  "资料里明确提到的卖点：限量、手工、当季、可试穿、可预约等",
  "情绪与场景结论（把喧嚣留在门外、从灯光里讨一点温暖）",
  "行动号召（到店试穿、周末来坐坐、限时三日）"
];

const NEGATIVE_LIMIT = 18;
const POSITIVE_LIMIT = 18;

/** 生成给模型看的文案规则片段（规则 + 正反例 + 改写对照）。 */
export function buildCopyRulesPrompt(): string {
  const negative = COPY_NEGATIVE_EXAMPLES.slice(0, NEGATIVE_LIMIT);
  const positive = COPY_POSITIVE_EXAMPLES.slice(0, POSITIVE_LIMIT);
  const rewrites = COPY_REWRITE_EXAMPLES.slice(0, 8);

  return [
    "【文案能写什么 / 不能写什么（正反例，务必逐条对照）】",
    "三条禁令：",
    "① 禁止描述图片本身：视角、构图、光线方向、色调、材质反光、器材、景别，一律不写。",
    "② 禁止写设计心思与手法：反差、层次、留白、呼吸感、视觉重心、描边、压字，这些只写进 concept。",
    "③ 禁止描写主体与画面的基础特征：衣服颜色/款式、裤子、鞋、发型、镜头的距离与角度、整体色调；",
    "   只有资料里明确写「突出单品」「突出穿搭」「突出摄影」时，才允许写这几项，而且必须挑资料提到的单品；",
    "   资料只是顺带提一句「我很满意那天的穿搭」而没说「要突出」，也算不允许。",
    "",
    "反例（看到这种写法就重写）✗：",
    ...negative.map((item) => `- ${item}`),
    "",
    "正例（这才是画面文案）✓：",
    ...positive.map((item) => `- ${item}`),
    "",
    "可以放心使用的信息类型：",
    ...COPY_ALLOWED_KINDS.map((item) => `- ${item}`),
    "",
    "改写示范（左边是错的，右边才是该写的）：",
    ...rewrites.map((item) => `- ✗ ${item.wrong}\n  ✓ ${item.right}（${item.why}）`)
  ].join("\n");
}
